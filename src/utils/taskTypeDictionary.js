/**
 * Returns translated label for task type according to active language
 * @param {object|string} task - Task object or Task Type Code
 * @param {string} language - Active language (e.g. 'en', 'tr', 'de', 'es', 'fr', 'it', 'ru', 'ar')
 * @returns {string} Translated task type name
 */
export function getTaskTypeLabel(task, language = 'en') {
  if (!task) return '';
  const lang = (language || 'en').toLowerCase();
  const code = typeof task === 'string' ? task : (task.taskTypeCode || task.code || '');

  // 1. Direct code lookup
  if (code && TASK_TYPE_LOCALES[code]) {
    const loc = TASK_TYPE_LOCALES[code];
    if (loc[lang]) return loc[lang];
    if (loc['en']) return loc['en'];
  }

  // 2. Normalized code lookup
  if (code) {
    const normCode = code.replace(/[-\s]/g, '_').toUpperCase();
    if (TASK_TYPE_LOCALES[normCode]) {
      const loc = TASK_TYPE_LOCALES[normCode];
      if (loc[lang]) return loc[lang];
      if (loc['en']) return loc['en'];
    }
  }

  // 3. Name translations object embedded in task entity
  const rawTrans = typeof task === 'object' ? (task.nameTranslations || task.nameTranslationsJson) : null;
  if (rawTrans) {
    try {
      const trans = typeof rawTrans === 'string' ? JSON.parse(rawTrans) : rawTrans;
      if (trans && trans[lang]) return trans[lang];
      if (trans && trans['en']) return trans[lang] || trans['en'];
      if (trans && trans['tr']) return trans['tr'];
    } catch (e) {
      // ignore
    }
  }

  // 4. Reverse lookup by known taskTypeName
  const taskName = typeof task === 'object' ? (task.taskTypeName || task.name) : null;
  if (taskName) {
    for (const item of Object.values(TASK_TYPE_LOCALES)) {
      if (item.tr === taskName || item.en === taskName) {
        if (item[lang]) return item[lang];
        if (item['en']) return item['en'];
      }
    }
    return taskName;
  }

  return code || '';
}
